#!/bin/sh
# Regenerates sql/005_pin.sql from the pinned upstream image.
set -eu

root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
env_file=$root/tools/fixture/upstream.env
# shellcheck source=tools/fixture/upstream.env
. "$env_file"

compose="docker compose -f $root/tools/fixture/docker-compose.yaml --env-file $env_file"

$compose up -d --wait db
$compose run --rm --quiet-pull migrate

query() {
    $compose exec -T db psql -U postgres -d postgres -Atc "$1"
}

count=$(query "SELECT count(*) FROM _sqlx_migrations WHERE success")
latest=$(query "SELECT max(version) FROM _sqlx_migrations WHERE success")
digest=$(query "SELECT md5(string_agg(version::text || ':' || encode(checksum, 'hex'), ',' ORDER BY version)) FROM _sqlx_migrations WHERE success")

cat > "$root/sql/005_pin.sql" <<PIN
-- Generated by tools/repin.sh from $LAKEKEEPER_IMAGE
-- $LAKEKEEPER_DIGEST
CREATE FUNCTION @extschema@._pin()
RETURNS TABLE (
    upstream_sha     text,
    upstream_version text,
    migration_count  integer,
    latest_version   bigint,
    migration_digest text
)
LANGUAGE sql IMMUTABLE
AS \$body\$
SELECT '$LAKEKEEPER_SHA'::text,
       '$LAKEKEEPER_VERSION'::text,
       $count::integer,
       $latest::bigint,
       '$digest'::text
\$body\$;

COMMENT ON FUNCTION @extschema@._pin() IS
    'The upstream Lakekeeper build this extension version was written against.';
PIN

printf 'sql/005_pin.sql: %s, %s migrations, latest %s\n' "$LAKEKEEPER_SHA" "$count" "$latest"
